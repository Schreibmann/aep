import {
  AEP_CONFIG_VERSION,
  type AepProjectConfig,
  parseAepProjectConfig,
} from "./config-schema.js";
import type { StackDetectionReport } from "./types.js";

export type BuildConfigInput = {
  readonly detection: StackDetectionReport;
  /** Gate script names the user explicitly approved. */
  readonly approvedGateScripts?: ReadonlyArray<string>;
  /** When true, auto-approve high-confidence exact gate scripts only. */
  readonly autoApproveExactGates?: boolean;
  readonly allowlistedModelIds?: ReadonlyArray<string>;
  readonly allowPotentialExtraCharge?: boolean;
  readonly detectedAt?: string;
};

/**
 * Build a validated AEP project config from detection + explicit approvals.
 * Ambiguous scripts stay in pendingConfirmation until approved.
 */
export function buildProjectConfigFromDetection(input: BuildConfigInput): AepProjectConfig {
  const exactHigh = input.detection.scripts
    .filter((script) => script.suggestedGate !== undefined && !script.needsConfirmation)
    .map((script) => script.name);

  const approved = new Set<string>([
    ...(input.approvedGateScripts ?? []),
    ...(input.autoApproveExactGates === true ? exactHigh : []),
  ]);

  const pending = input.detection.ambiguousScripts
    .map((script) => script.name)
    .filter((name) => !approved.has(name));

  return parseAepProjectConfig({
    version: AEP_CONFIG_VERSION,
    runtime: "fake",
    sandbox: { enabled: true },
    packageManager:
      input.detection.packageManager.id === "unknown"
        ? undefined
        : input.detection.packageManager.id,
    limits: { maxFixCycles: 2 },
    gates: {
      approvedScriptNames: [...approved],
      pendingConfirmation: pending,
    },
    models: {
      allowlistedModelIds: [...(input.allowlistedModelIds ?? [])],
      allowPotentialExtraCharge: input.allowPotentialExtraCharge === true,
    },
    detection: {
      ...(input.detection.packageName === undefined
        ? {}
        : { packageName: input.detection.packageName }),
      frameworks: input.detection.frameworks.map((f) => f.id),
      ...(input.detectedAt === undefined ? {} : { detectedAt: input.detectedAt }),
    },
  });
}

export function renderProjectConfigYaml(config: AepProjectConfig): string {
  const lines = [
    "# AEP project config — generated by `aep init`",
    "# Do not store secrets or API keys in this file.",
    `version: ${config.version}`,
    `runtime: ${config.runtime}`,
    "sandbox:",
    "  enabled: true",
  ];
  if (config.packageManager !== undefined) {
    lines.push(`packageManager: ${config.packageManager}`);
  }
  lines.push("limits:", `  maxFixCycles: ${config.limits.maxFixCycles}`);
  lines.push("gates:");
  lines.push("  approvedScriptNames:");
  if (config.gates.approvedScriptNames.length === 0) {
    lines.push("    []");
  } else {
    for (const name of config.gates.approvedScriptNames) {
      lines.push(`    - ${JSON.stringify(name)}`);
    }
  }
  lines.push("  pendingConfirmation:");
  if (config.gates.pendingConfirmation.length === 0) {
    lines.push("    []");
  } else {
    for (const name of config.gates.pendingConfirmation) {
      lines.push(`    - ${JSON.stringify(name)}`);
    }
  }
  lines.push("models:");
  lines.push("  allowPotentialExtraCharge: false");
  lines.push("  allowlistedModelIds:");
  if (config.models.allowlistedModelIds.length === 0) {
    lines.push("    []");
  } else {
    for (const id of config.models.allowlistedModelIds) {
      lines.push(`    - ${JSON.stringify(id)}`);
    }
  }
  if (config.detection !== undefined) {
    lines.push("detection:");
    if (config.detection.packageName !== undefined) {
      lines.push(`  packageName: ${JSON.stringify(config.detection.packageName)}`);
    }
    lines.push("  frameworks:");
    if (config.detection.frameworks.length === 0) {
      lines.push("    []");
    } else {
      for (const id of config.detection.frameworks) {
        lines.push(`    - ${JSON.stringify(id)}`);
      }
    }
    if (config.detection.detectedAt !== undefined) {
      lines.push(`  detectedAt: ${JSON.stringify(config.detection.detectedAt)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}
